// Generates platform constant files from presets/presets.json.
// Run with `npm run gen` after editing the JSON.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const presets = JSON.parse(readFileSync(root + "presets/presets.json", "utf8"));
// Every variant gets its own tilt and spin (falling back to the defaults), so platform
// code can read them per variant without special cases.
for (const [name, v] of Object.entries(presets.variants)) {
  presets.variants[name] = { tilt: presets.defaults.tilt, spin: presets.defaults.spin, ...v };
}
const header = "// Generated by scripts/gen-presets.mjs from presets/presets.json. Do not edit.";
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const num = (v) => (Number.isInteger(v) ? `${v}` : `${v}`);
const dbl = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

function ts() {
  const obj = (o) => "{ " + Object.entries(o).map(([k, v]) => `${k}: ${num(v)}`).join(", ") + " }";
  const lines = [header, "", `export const DEFAULTS = ${obj(presets.defaults)} as const;`, "", "export const VARIANTS = {"];
  for (const [name, o] of Object.entries(presets.variants)) lines.push(`  ${name}: ${obj(o)},`);
  lines.push("} as const;", "", "export type Variant = keyof typeof VARIANTS;", "");
  return lines.join("\n");
}

function swift() {
  const block = (name, o, indent) => {
    const pad = "    ".repeat(indent);
    const out = [`${pad}public enum ${name} {`];
    for (const [k, v] of Object.entries(o)) {
      out.push(k === "count" ? `${pad}    public static let ${k} = ${v}` : `${pad}    public static let ${k}: Double = ${dbl(v)}`);
    }
    out.push(`${pad}}`);
    return out.join("\n");
  };
  const parts = [header, "", "public enum Presets {", block("Defaults", presets.defaults, 1)];
  for (const [name, o] of Object.entries(presets.variants)) parts.push(block(cap(name), o, 1));
  parts.push("}", "");
  return parts.join("\n");
}

function kotlin() {
  const block = (name, o) => {
    const out = [`    object ${name} {`];
    for (const [k, v] of Object.entries(o)) {
      out.push(k === "count" ? `        const val ${k}: Int = ${v}` : `        const val ${k}: Double = ${dbl(v)}`);
    }
    out.push("    }");
    return out.join("\n");
  };
  const parts = [header, "", "package io.github.oddedd.soom", "", "object Presets {", block("Defaults", presets.defaults)];
  for (const [name, o] of Object.entries(presets.variants)) parts.push(block(cap(name), o));
  parts.push("}", "");
  return parts.join("\n");
}

writeFileSync(root + "packages/web/src/presets.ts", ts());
writeFileSync(root + "ios/Sources/Soom/Presets.swift", swift());
writeFileSync(root + "android/soom/src/main/kotlin/io/github/oddedd/soom/Presets.kt", kotlin());
console.log("presets generated for web, iOS, Android");
